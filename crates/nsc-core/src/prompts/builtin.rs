//! 内置 prompt 模板。
//!
//! 模板格式规范:
//! - `---` 独占一行切分 system / user 两段(spec § 模板格式)。
//! - 占位符 `{{var}}` 双花括号;变量集见 `prompts::render`。
//! - 内置模板结尾必须包含硬性输出约束(不要输出章节标题 / 元注释 / "待续" 等),
//!   防止 LLM 在 content 前后贴心地附加结构化前缀,污染 `workflow_result_chapters.content` 存储。
//! - 模板正文里的引号一律用全角 “ ”,不要用 ASCII `"` —— Rust 字符串字面量里
//!   裸 `"` 会直接截断字符串。
//!
//! ## 模板设计要点(改模板前先读)
//! 1. **量化目标**:压缩给压缩比区间,风格转换给句长/段落/对话占比等可核对的指标。
//!    没有量化目标的"改写/压缩"指令,模型会退化为轻度改写(压缩比失控)。
//! 2. **可判定准绳**:删/留判据要能被模型逐条核对(如"一段里没有新信息且无对话 → 删"),
//!    不能写成"删不影响剧情推进的段落"这种主观标准 —— 主观标准的结果是模型一律不删。
//! 3. **风格锚点分工**:压缩用 `{{prev_original}}`(原作风格就是目标风格,压缩不换文风);
//!    风格转换用 `{{prev_transformed}}`(要延续的是上一章**产出**的风格,看原作锚点等于锚错方向)。
//! 4. **上下文只读**:邻章三块是参考材料,必须显式声明不得输出、不得混入正文,
//!    否则模型可能把邻章内容当成本章续写素材。
//! 5. **跨章一致性**:多章并发转换时人名/译名/专名漂移是最常见崩坏点,需显式约束。
//! 6. 正向要求优先于纯禁令:"只输出正文,第一行即正文第一个字"比"不要输出标题"有效。

use crate::models::PromptKind;

#[derive(Debug, Clone)]
pub struct BuiltinPrompt {
    pub name: &'static str,
    pub kind: PromptKind,
    pub template: &'static str,
}

pub fn builtin_prompts() -> Vec<BuiltinPrompt> {
    vec![
        BuiltinPrompt {
            name: "compress_default",
            kind: PromptKind::Compress,
            template: COMPRESS_DEFAULT,
        },
        BuiltinPrompt {
            name: "style_default",
            kind: PromptKind::Style,
            template: STYLE_DEFAULT,
        },
    ]
}

const COMPRESS_DEFAULT: &str = "\
你是一名专业小说编辑,任务是压缩章节:保留全部情节信息,删掉承载信息的冗余文字。
压缩目标:输出长度为原文的 30%–50%,按情节密度自适应 ——
- 原文实写事件多、对话多、信息密 → 取 45%–50%(接近上限,不许丢细节);
- 原文多为环境描写、心理独白、重复叙述 → 取 30%–35%(接近下限,狠删水词)。
上限下限都是硬约束:不得低于 30%(丢情节),不得超过 50%(等于没压缩)。
只压缩,不改文风:叙述腔调、人称、时态、段落顺序保持原样,这不是润色任务。
---
# 参考材料(只读,禁止输出、禁止混入正文)
以下邻章仅用于理解上下文与人名、称呼一致性,不要改写它们,也不要在输出里复述。
每章最多 {{prev_context_budget}} 字、合计最多 {{total_context_budget}} 字,超出部分会被省略并标为
“…(因长度限制,此处省略若干段落)…”。省略段只是没放进本次请求,并非原文缺失,不要据此补写或推断。
## 上一章原文
{{prev_original}}

## 上一章改写后(若有)
{{prev_transformed}}

## 下一章原文(若有)
{{next_original}}

# 待压缩章节
章节标题:{{chapter_title}}
正文:
<<<CHAPTER_BEGIN>>>
{{chapter_content}}
<<<CHAPTER_END>>>

# 压缩规则(逐条执行)
保留(必须完整留下的信息):
1. 每一个推进或转折剧情的动作、决定、结果 —— 谁做了什么、导致了什么。
2. 所有对话的**信息与立场**:谁对谁说了什么、态度如何。允许压缩说话标签与寒暄客套,
   但不得删除对话所传达的信息、态度转折与关键台词。
3. 出场人物的姓名、身份、关系、称呼,以及关键道具 / 地点 / 数值 / 时间点。
4. 伏笔、悬念、埋线 —— 即使只有半句,也原样保留。

删除或合并(可判定的判据,不是主观取舍):
5. 同一信息被重复表达的段落:只留最早出现且最完整的一处,其余删除。
6. 一整段既无新信息、又无对话、也无动作(纯景物铺陈、情绪复述、心理解释)→ 整段删除。
7. 连续的多段心理独白 / 环境描写:合并为一句概括,概括只写原文已经写明的意思,不新增解读。
8. 同场景内可合并的过渡与过场:多个小节合并为一段,删掉场景切换前后的铺垫文字。
9. 修饰性堆叠(连续形容词、比喻、排比)→ 保留最有力的一个,其余删除。

保留边界:压缩只做删减与合并,不得改写句子结构以“让它更顺”,不得改变事件顺序,
不得把原文的间接引语改成直接引语(或反之),不得新增原文没有的任何内容。

# 输出要求(违反任一条即视为失败)
- 只输出压缩后的章节正文。第一行就是正文的第一个字,最后一行就是正文结尾。
- 压缩比落在 30%–50% 区间。若你判断原文信息极密,取 50% 而不是继续精简。
- 不要输出章节标题、“压缩后”等标签、字数统计、说明、注释、“以下是压缩结果”、“待续”、“(完)”。
- 不要用 markdown 代码块包裹正文,不要用 ``` 围栏,不要输出 # 标题行。
- 全文使用与原文一致的人名、译名、专有名词与称谓,不得替换或简化。
- 分不出该不该删时:保留。信息完整优先于压缩率。";

const STYLE_DEFAULT: &str = "\
你是一名资深网文改写编辑。任务:把章节改写为节奏更快、画面感更强的现代网文风,供移动端阅读。
情节、人物、场景、结构一律不动,只改表达方式。
---
# 参考材料(只读,禁止输出、禁止混入正文)
邻章用于对齐文风与人名/称谓一致性,不要改写它们,也不要在输出里复述。
每章最多 {{prev_context_budget}} 字、合计最多 {{total_context_budget}} 字,超出部分会被省略并标为
“…(因长度限制,此处省略若干段落)…”。省略段只是没放进本次请求,并非原文缺失,不要据此补写或推断。
## 上一章原文
{{prev_original}}

## 上一章改写后(风格锚点,优先对齐)
{{prev_transformed}}

## 下一章原文(若有)
{{next_original}}

# 待改写章节
章节标题:{{chapter_title}}
正文:
<<<CHAPTER_BEGIN>>>
{{chapter_content}}
<<<CHAPTER_END>>>

# 目标文风(逐条达标,这些指标是可以核对的)
1. 句长:句子平均不超过 25 字,长句拆成短句。允许极短句(3–8 字)制造节奏,
   但不要通篇碎句 —— 叙述句保持完整主谓。
2. 段落:每段 1–3 句,超过 3 句必须拆段。对话独立成段,一段内不要混排多人的话。
3. 对话:提高对话与动作的比重,由对话与动作承载情绪,而不是由叙述解释情绪。
4. 描写:环境与心理描写压到必要限度,优先保留能推动情节或暗示情绪的那一句。
5. 动词:优先具体动词与身体动作(“他把杯子磕在桌上”),避免“感到”“似乎”“彷佛”这类虚写堆叠。
6. 节奏:紧张处短句连排,舒缓处可稍长,但不得整章同一节奏。
7. 若提供“上一章改写后”,本章的句长密度、对话语气、称呼与用词必须与它保持一致;
   若未提供,以原文风格为基线,只做上述指标内的收紧。

# 允许的改动 / 禁止的改动
允许:
- 调整句子切分与段落切分;调整语序使句子更顺;把叙述性情绪描写改写为动作或对话。
- 替换表述方式(如“他非常生气” → “他一把掀了桌子”),只要语义等价。
禁止(违反即视为失败):
- 不新增情节、场景、人物、对话内容、伏笔或任何原文没有的信息。不得为了衔接而补写过渡段落。
- 不删情节:原文出现的动作、对话、信息量必须全部保留,只换表达方式。
- 不改变人称、时态、叙事视角,不改变事件发生顺序,不改变段落先后。
- 不改变人物性格与说话方式(粗鲁的角色不能改成文雅)。
- 不改人名、译名、专有名词、称呼、数值。

# 输出要求(违反任一条即视为失败)
- 只输出改写后的章节正文。第一行就是正文的第一个字,最后一行就是正文结尾。
- 篇幅与原文相当(±15%),不得为了“紧凑”而缩写成梗概,也不得注水拉长。
- 不要输出章节标题、“改写后”等标签、字数统计、说明、注释、“以下是改写结果”、“待续”、“(完)”。
- 不要用 markdown 代码块包裹正文,不要用 ``` 围栏,不要输出 # 标题行。
- 全文使用与原文一致的人名、译名、专有名词与称谓,不得替换或简化。";

#[cfg(test)]
mod tests {
    use super::*;

    fn template(name: &str) -> &'static str {
        builtin_prompts()
            .into_iter()
            .find(|p| p.name == name)
            .unwrap_or_else(|| panic!("builtin prompt {name} missing"))
            .template
    }

    /// 两个内置模板都必须能被 render 切出 system 段(`---` 独占一行),
    /// 且引用章节正文占位符 —— 否则 LLM 看不到正文 / 拿不到角色约束。
    #[test]
    fn both_templates_have_system_section_and_chapter_content() {
        for name in ["compress_default", "style_default"] {
            let t = template(name);
            assert!(
                t.lines().any(|l| l.trim() == "---"),
                "{name}: 缺少独占一行的 --- ,system 段会丢失"
            );
            assert!(
                t.contains("{{chapter_content}}"),
                "{name}: 缺 chapter_content 占位符"
            );
            for var in [
                "{{chapter_title}}",
                "{{prev_original}}",
                "{{prev_transformed}}",
                "{{next_original}}",
            ] {
                assert!(t.contains(var), "{name}: 缺 {var}");
            }
        }
    }

    /// 量化目标必须留在模板里:压缩比区间 / 句长上限。
    /// 这两条是"提示词是否足够强"的核心 —— 删掉它们模型会退化成轻度改写。
    #[test]
    fn templates_keep_quantified_targets() {
        let compress = template("compress_default");
        assert!(compress.contains("30%"), "compress: 缺压缩比下限");
        assert!(compress.contains("50%"), "compress: 缺压缩比上限");

        let style = template("style_default");
        assert!(style.contains("25 字"), "style: 缺句长上限");
    }

    /// 风格锚点分工:压缩锚原作(压缩不换文风),风格转换锚上一章**产出**。
    #[test]
    fn style_template_anchors_on_prev_transformed() {
        let style = template("style_default");
        let anchored = style
            .split("{{prev_transformed}}")
            .next()
            .and_then(|before| before.lines().next_back())
            .is_some_and(|line| line.contains("风格锚点"));
        assert!(anchored, "style: prev_transformed 上方必须标注为风格锚点");
    }
}

-- 量测产出的压缩/改写比例,并在越出护栏时落一条异常说明。
--
-- 背景:提示词里的「压缩到 30%–50%」「篇幅与原文相当」此前只是给模型的指令,
-- 系统从不实测输出长度 —— 无法回答"到底压到多少了"。本列存实际量测结果。
--
-- 设计取舍:
-- - 只存**越界时的说明文本**,NULL = 比例落在护栏内(或本次调用无可比输入,如 test_model)。
--   原始比例由 response_size / 输入字符数 可复算,不单开一列(避免两份真相)。
-- - 纯量测:**不**据此判 job 失败、**不**自动重试(重试会让每章最坏多花一次调用)。
--   越界只做可见化,由用户在 AI 调用页定位问题章节后决定是否重跑。
-- - 护栏区间只抓真异常(压缩 <15% / >90%,文风 <50% / >200%),与提示词的
--   30%–50% 目标区间刻意不重合 —— 目标是引导,护栏是失败检测,重合会造成大量误报。
--
